// Font atlas: 128x128, 16x16 grid of 8x8 chars
static uint8_t s_atlas[128 * 128];

static void buildAtlas()
{
    std::memset(s_atlas, 0, sizeof(s_atlas));

    for (int c = 32; c < 128; ++c)
    {
        int gx = c % 16, gy = c / 16;
        int ax = gx * 8, ay = gy * 8;
        int fi = (c - 32) * 8;
        for (int row = 0; row < 8; ++row)
        {
            uint8_t bits = kFont8x8[fi + row];
            for (int col = 0; col < 8; ++col)
                s_atlas[(ay + row) * 128 + (ax + col)] = ((bits >> (7 - col)) & 1) ? 255 : 0;
        }
    }
    // Block char
    for (int r = 0; r < 8; ++r)
        for (int c = 0; c < 8; ++c)
            s_atlas[(15 * 8 + r) * 128 + (15 * 8 + c)] = 255;
}

static const char* kVS = R"GLSL(
#version 450 core
in vec2 aPos;
in vec2 aUV;
in vec4 aColor;
uniform vec2 uScreenSize;
out vec2 vUV;
out vec4 vColor;
void main(){
    vec2 ndc = (aPos / uScreenSize) * 2.0 - 1.0;
    ndc.y = -ndc.y;
    gl_Position = vec4(ndc, 0.9999, 1.0);
    vUV = aUV;
    vColor = aColor;
})GLSL";

static const char* kFS = R"GLSL(
#version 450 core
in vec2 vUV;
in vec4 vColor;
uniform sampler2D uTex;
out vec4 fragColor;
void main(){
    float a = texture(uTex, vUV).r;
    if(a < 0.1) discard;
    fragColor = vec4(vColor.rgb, vColor.a * a);
})GLSL";

static uint32_t mkProg(const char* vs, const char* fs)
{
    GLuint v = glCreateShader(GL_VERTEX_SHADER);
    glShaderSource(v, 1, &vs, nullptr);
    glCompileShader(v);
    GLuint f = glCreateShader(GL_FRAGMENT_SHADER);
    glShaderSource(f, 1, &fs, nullptr);
    glCompileShader(f);
    GLuint p = glCreateProgram();
    glAttachShader(p, v); glAttachShader(p, f);
    glLinkProgram(p);
    glDeleteShader(v); glDeleteShader(f);
    return p;
}

// Emit one quad (2 triangles, 6 verts) into s_vbuf
void Text2D::emitQuad(float x, float y, float w, float h,
                     float u0, float v0, float u1, float v1,
                     float r, float g, float b, float a)
{
    // If no texture coords (fill rect), use the block char at (15,15)
    // which is all 255 so texture alpha = 1.0
    float tu0 = u0, tv0 = v0, tu1 = u1, tv1 = v1;
    if (u0 == 0 && v0 == 0 && u1 == 0 && v1 == 0)
    {
        tu0 = (float)(15 * 8) / 128.0f;
        tv0 = (float)(15 * 8) / 128.0f;
        tu1 = tu0 + 8.0f / 128.0f;
        tv1 = tv0 + 8.0f / 128.0f;
    }

    int base = Text2D::s_vertexCount * Text2D::kFloatsPerVertex;

    const float verts[6][7] = {
        {x,   y,   tu0, tv0, r, g, b},
        {x+w, y,   tu1, tv0, r, g, b},
        {x,   y+h, tu0, tv1, r, g, b},
        {x+w, y,   tu1, tv0, r, g, b},
        {x+w, y+h, tu1, tv1, r, g, b},
        {x,   y+h, tu0, tv1, r, g, b},
    };

    for (int i = 0; i < 6; ++i)
    {
        s_vbuf[base + i * 7 + 0] = verts[i][0];
        s_vbuf[base + i * 7 + 1] = verts[i][1];
        s_vbuf[base + i * 7 + 2] = verts[i][2];
        s_vbuf[base + i * 7 + 3] = verts[i][3];
        s_vbuf[base + i * 7 + 4] = verts[i][4];
        s_vbuf[base + i * 7 + 5] = verts[i][5];
        s_vbuf[base + i * 7 + 6] = a;
    }
    Text2D::s_vertexCount += 6;
}

void Text2D::init()
{
    if (s_initialized) return;
    s_initialized = true;

    buildAtlas();

    glGenTextures(1, &s_fontTex);
    glBindTexture(GL_TEXTURE_2D, s_fontTex);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_R8, 128, 128, 0, GL_RED, GL_UNSIGNED_BYTE, s_atlas);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);

    s_prog = mkProg(kVS, kFS);

    glGenBuffers(1, &s_vbo);
}

void Text2D::shutdown()
{
    if (s_fontTex) glDeleteTextures(1, &s_fontTex);
    if (s_prog) glDeleteProgram(s_prog);
    if (s_vbo) glDeleteBuffers(1, &s_vbo);
    s_initialized = false;
}

void Text2D::begin(int screenW, int screenH)
{
    s_inFrame = true;
    s_screenW = screenW;
    s_screenH = screenH;
    s_vertexCount = 0;
}

void Text2D::end()
{
    if (!s_inFrame) return;
    flush();
    s_inFrame = false;
}

void Text2D::drawFill(int x, int y, int w, int h, Vec4 color)
{
    if (s_vertexCount / kVertsPerQuad >= kMaxQuads) flush();
    emitQuad((float)x, (float)y, (float)w, (float)h,
             0,0,0,0, color.x, color.y, color.z, color.w);
}

void Text2D::drawChar(int x, int y, int charCode, Vec4 color)
{
    if (charCode < 0 || charCode > 255) charCode = 255;
    if (s_vertexCount / kVertsPerQuad >= kMaxQuads) flush();

    int gx = charCode % 16, gy = charCode / 16;
    float u0 = (float)(gx * 8) / 128.0f;
    float v0 = (float)(gy * 8) / 128.0f;
    float u1 = u0 + 8.0f / 128.0f;
    float v1 = v0 + 8.0f / 128.0f;

    emitQuad((float)x, (float)y, 8.0f, 8.0f,
             u0, v0, u1, v1, color.x, color.y, color.z, color.w);
}

void Text2D::drawString(int x, int y, const char* text, Vec4 color)
{
    int cx = x;
    while (*text)
    {
        unsigned char c = (unsigned char)*text;
        drawChar(cx, y, c, color);
        cx += 8;
        ++text;
    }
}

int Text2D::stringWidth(const char* text)
{
    int w = 0;
    while (*text) { w += 8; ++text; }
    return w;
}

void Text2D::flush()
{
    if (s_vertexCount == 0) return;

    // Save ALL state we modify
    GLint prevProg, prevVAO, prevTexUnit, prevTex2D, prevBlend, prevDepth, prevCull, prevSRGB;
    glGetIntegerv(GL_CURRENT_PROGRAM, &prevProg);
    glGetIntegerv(GL_VERTEX_ARRAY_BINDING, &prevVAO);
    glGetIntegerv(GL_ACTIVE_TEXTURE, &prevTexUnit);
    glGetIntegerv(GL_TEXTURE_BINDING_2D, &prevTex2D);
    glGetIntegerv(GL_BLEND, &prevBlend);
    glGetIntegerv(GL_DEPTH_TEST, &prevDepth);
    glGetIntegerv(GL_CULL_FACE, &prevCull);
    glGetIntegerv(GL_FRAMEBUFFER_SRGB, &prevSRGB);

    // Setup for 2D overlay
    glDisable(GL_DEPTH_TEST);
    glDisable(GL_CULL_FACE);
    glDisable(GL_FRAMEBUFFER_SRGB);
    glEnable(GL_BLEND);
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    // Bind shader
    glUseProgram(s_prog);
    glUniform2f(glGetUniformLocation(s_prog, "uScreenSize"), (float)s_screenW, (float)s_screenH);

    // Bind texture
    glActiveTexture(GL_TEXTURE0);
    glBindTexture(GL_TEXTURE_2D, s_fontTex);
    glUniform1i(glGetUniformLocation(s_prog, "uTex"), 0);

    // Upload and draw using VAO=0 (no VAO, just vertex attribs)
    glBindVertexArray(0);
    glBindBuffer(GL_ARRAY_BUFFER, s_vbo);
    glBufferData(GL_ARRAY_BUFFER, s_vertexCount * sizeof(float) * kFloatsPerVertex,
                 s_vbuf, GL_STREAM_DRAW);

    const int stride = sizeof(float) * kFloatsPerVertex;
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, stride, (void*)0);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(1, 2, GL_FLOAT, GL_FALSE, stride, (void*)(sizeof(float) * 2));
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(2, 4, GL_FLOAT, GL_FALSE, stride, (void*)(sizeof(float) * 4));
    glEnableVertexAttribArray(2);

    glDrawArrays(GL_TRIANGLES, 0, s_vertexCount);

    // Restore ALL state
    glBindVertexArray(prevVAO);
    glActiveTexture(prevTexUnit);
    glBindTexture(GL_TEXTURE_2D, prevTex2D);
    glUseProgram(prevProg);
    if (prevBlend) glEnable(GL_BLEND); else glDisable(GL_BLEND);
    if (prevDepth) glEnable(GL_DEPTH_TEST); else glDisable(GL_DEPTH_TEST);
    if (prevCull) glEnable(GL_CULL_FACE); else glDisable(GL_CULL_FACE);
    if (prevSRGB) glEnable(GL_FRAMEBUFFER_SRGB);

    s_vertexCount = 0;
}

